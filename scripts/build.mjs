import { readFile, writeFile } from "node:fs/promises";
import { resolve } from "node:path";

/**
 * Tiny zero-dependency bundler.
 *
 * The source stays in readable ES modules (used by node:test), but browsers
 * block module imports on file:// because the origin is "null". This script
 * converts the modules into one classic script so index.html works when opened
 * by double-click, without a server or a build step for the user.
 *
 * Supported syntax (all this project uses):
 *   import { a, b } from "./module.js";
 *   export function name() {}
 *   export const name = ...;
 *   export let name = ...;
 *   export class Name {}
 */

const jsDir = resolve("js");
const entry = "./app.js";
const outputFile = resolve(jsDir, "bundle.js");

const moduleFiles = [
  "./formatters.js",
  "./schema.js",
  "./validators.js",
  "./draft.js",
  "./form-builder.js",
  "./app.js",
];

const IMPORT_RE =
  /^[ \t]*import\s*\{([\s\S]*?)\}\s*from\s*["']([^"']+)["'];?[ \t]*$/gm;
const EXPORT_RE =
  /^[ \t]*export\s+(function|const|let|class)\s+([A-Za-z_$][\w$]*)/gm;

function normalizeId(id) {
  return id.startsWith("./") ? id : `./${id}`;
}

function parseImportNames(specifiers) {
  return specifiers
    .split(",")
    .map((specifier) => specifier.trim())
    .filter(Boolean)
    .map((specifier) => {
      const [imported, local] = specifier.split(/\s+as\s+/);
      return local ? `${imported.trim()}: ${local.trim()}` : imported.trim();
    });
}

function transformModule(id, source) {
  const exportedNames = [];
  let code = source.replace(/\r\n/g, "\n");

  code = code.replace(IMPORT_RE, (_, specifiers, importPath) => {
    const names = parseImportNames(specifiers).join(", ");
    return `const { ${names} } = __require(${JSON.stringify(normalizeId(importPath))});`;
  });

  code = code.replace(EXPORT_RE, (_, kind, name) => {
    exportedNames.push(name);
    return `${kind} ${name}`;
  });

  if (/^\s*export\s/m.test(code)) {
    throw new Error(`Unsupported export syntax left in ${id}`);
  }

  const exportLines = exportedNames
    .map((name) => `  exports.${name} = ${name};`)
    .join("\n");

  return `__modules[${JSON.stringify(id)}] = function (exports) {\n${code}\n${exportLines}\n};\n`;
}

const modules = [];
for (const id of moduleFiles) {
  const source = await readFile(resolve(jsDir, id.slice(2)), "utf8");
  modules.push(transformModule(id, source));
}

const bundle = `/*
 * Generated by scripts/build.mjs from js/*.js — do not edit by hand.
 * Classic script so the page also works from file:// (ES modules are blocked
 * there by the browser because the origin is "null").
 */
(function () {
  "use strict";

  const __modules = {};
  const __cache = {};

  function __require(id) {
    if (__cache[id]) return __cache[id];
    const exports = {};
    __cache[id] = exports;
    __modules[id](exports);
    return exports;
  }

${modules.join("\n")}
  __require(${JSON.stringify(entry)});
})();
`;

await writeFile(outputFile, bundle, "utf8");
console.log(`Built js/bundle.js (${bundle.length} bytes, ${moduleFiles.length} modules).`);
